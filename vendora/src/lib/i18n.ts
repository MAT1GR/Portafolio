export const LANGUAGES: Record<string, { label: string; dict: Dict }> = {
  es: { label: "Español", dict: es },
  en: { label: "English", dict: en },
  pt: { label: "Português", dict: pt },
  it: { label: "Italiano", dict: it },
  fr: { label: "Français", dict: fr },
  de: { label: "Deutsch", dict: de },
  ro: { label: "Română", dict: ro },
  cs: { label: "Čeština", dict: cs },
  hu: { label: "Magyar", dict: hu },
  pl: { label: "Polski", dict: pl },
};

export function dict(lang: string): Dict {
  return (LANGUAGES[lang] || LANGUAGES.es).dict;
}

export function fill(template: string, params: Record<string, string | number> = {}) {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

export function t(lang: string, key: DictKey, params?: Record<string, string | number>) {
  return fill(dict(lang)[key], params);
}
